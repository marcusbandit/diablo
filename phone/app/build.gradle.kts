// Cleartext is allowed only to the tailnet hosts. Which ones is this box's business, so the
// list comes from DIABLO_CLEARTEXT_HOSTS in ~/.config/diablo/local.env (comma separated:
// Tailscale IPs, short names, the tailnet suffix) plus the MagicDNS short names below.
fun localEnv(): Map<String, String> {
    val path = System.getenv("DIABLO_LOCAL_ENV") ?: "${System.getProperty("user.home")}/.config/diablo/local.env"
    val file = File(path)
    if (!file.isFile) return emptyMap()
    return file.readLines().map { it.trim() }
        .filter { it.isNotEmpty() && !it.startsWith("#") && "=" in it }
        .associate { line ->
            val (key, value) = line.removePrefix("export ").split("=", limit = 2)
            key.trim() to value.trim().removeSurrounding("\"").removeSurrounding("'")
        }
}

val networkConfig = tasks.register("networkSecurityConfig") {
    description = "Writes res/xml/network_security_config.xml from this box's local.env"
    val hosts = (listOf("diablo-pi", "banditbox", "nemurenai", "kangaeru") +
        (System.getenv("DIABLO_CLEARTEXT_HOSTS") ?: localEnv()["DIABLO_CLEARTEXT_HOSTS"] ?: "")
            .split(",").map { it.trim() }.filter { it.isNotEmpty() }).distinct()
    inputs.property("hosts", hosts)
    val out = localRes.resolve("xml/network_security_config.xml")
    outputs.file(out)
    doLast {
        val domains = hosts.joinToString("\n") { host ->
            val sub = host.endsWith(".ts.net") && host.count { it == '.' } == 2
            "        <domain includeSubdomains=\"$sub\">$host</domain>"
        }
        out.parentFile.mkdirs()
        out.writeText(
            """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by the networkSecurityConfig task from local.env. Not in the repo. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
$domains
    </domain-config>
</network-security-config>
""",
        )
    }
}
