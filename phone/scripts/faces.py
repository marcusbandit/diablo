"""Copies Diablo's hand-drawn faces from assets/faces into the app at 256 px, and writes the require map."""
import json
import pathlib

from PIL import Image

MOODS = ["asleep", "resting", "listening", "expectant", "thinking", "working", "talking", "proud",
         "delighted", "sorry", "smug", "relieved", "wink", "surprised", "worried"]
here = pathlib.Path(__file__).resolve().parent
src = here.parent.parent / "assets" / "faces"
out = here.parent / "assets" / "faces"
lines = ["// Generated by scripts/faces.py from assets/faces. Do not edit.", "export const FACES = {"]
for mood in MOODS:
    (out / mood).mkdir(parents=True, exist_ok=True)
    frames = sorted(p for p in (src / mood).glob("*.png"))
    for p in frames:
        Image.open(p).convert("LA").resize((256, 256), Image.LANCZOS).save(out / mood / p.name, optimize=True)
    files = ", ".join(f'require("../../assets/faces/{mood}/{p.name}")' for p in frames)
    lines.append(f"  {mood}: [{files}],")
lines.append("} as const;")
lines.append("")
lines.append("export type Mood = keyof typeof FACES;")
(here.parent / "src" / "ui" / "faces.ts").write_text("\n".join(lines) + "\n")
print(json.dumps({m: len(list((out / m).glob('*.png'))) for m in MOODS}))
