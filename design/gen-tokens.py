#!/usr/bin/env python3
"""Regenerate tokens.css from tokens.json. The json is the source."""
import json
from pathlib import Path

root = Path(__file__).parent
tokens = json.loads((root / "tokens.json").read_text())

lines = ["/* generated by gen-tokens.py from tokens.json, do not edit by hand */", ":root {"]
for name, value in tokens["sizes"].items():
    lines.append(f"  --fs-{name}: {value};")
for group in ("colors", "type-colors", "faces", "spacing", "motion"):
    for name, value in tokens[group].items():
        lines.append(f"  --{name}: {value};")
lines.append("}")
(root / "tokens.css").write_text("\n".join(lines) + "\n")
print("tokens.css written")
